
package singledimensionalarray;

public class SingledimensionalArray {

    public static void main(String[] args) {
       int grades[] = {10, 20, 30, 40, 50};
       
       for (int i = 0; i < grades.length; i++) {
         
            System.out.print(grades[i] + " ");
            
        }   
    }
}

    
    
